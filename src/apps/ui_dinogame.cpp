DinoGameView::DinoGameView() {
    set_focusable(true);
    /* Seed the obstacle/bird RNG once, from the wall clock. */
    std::srand(static_cast<unsigned>(
        std::chrono::steady_clock::now().time_since_epoch().count()));
    new_game();
    state_ = State::MENU;
}

void DinoGameView::on_show() {
    View::on_show();
    focus();
    set_dirty();
}

void DinoGameView::focus() {
    ui::Widget::focus();
}

std::string DinoGameView::score_to_string(uint32_t score) {
    return zero_pad5(score);
}

void DinoGameView::new_game() {
    jump_ = Jump{};
    obstacle_ = Obstacle{};
    bird_in_game_ = false;
    bird_x_ = kScreenWidth;
    bird_y_offset_ = 0;
    bird_y_velocity_ = 0;
    bird_flop_ = false;
    ducking_ = false;
    duck_timer_ = 0;
    run_frame_ = false;
    collided_ = false;
    speed_modifier_ = 0;
    steps_ = 0;
    score_ = 0;
    obstacle_spawn_timer_ = 100;  /* initial delay before first obstacle */
    ground_offset_ = 0;
}

void DinoGameView::update_obstacle() {
    const int speed = kGameSpeedBase + speed_modifier_;

    if (obstacle_.active) {
        obstacle_.move(speed_modifier_);
        if (obstacle_.x < -50) obstacle_.active = false;
    }

    if (obstacle_spawn_timer_ > 0) obstacle_spawn_timer_ -= speed;

    if (obstacle_spawn_timer_ <= 0 && !obstacle_.active) {
        obstacle_.active = true;
        obstacle_.x = kScreenWidth;
        const int type = std::rand() % 4;
        switch (type) {
            case 0: obstacle_.width = 15; obstacle_.height = 25; break;
            case 1: obstacle_.width = 20; obstacle_.height = 35; break;
            case 2: obstacle_.width = 35; obstacle_.height = 30; break;
            default: obstacle_.width = 45; obstacle_.height = 28; break;
        }
        obstacle_spawn_timer_ =
            kMinObstacleDist + (std::rand() % (kMaxObstacleDist - kMinObstacleDist));
    }
}

void DinoGameView::manage_bird() {
    if (!bird_in_game_) {
        bool obstacle_nearby =
            obstacle_.active && obstacle_.x > (kScreenWidth * 4) / 5;
        if (!obstacle_nearby && (std::rand() % 400) == 0 && steps_ > 100) {
            bird_in_game_ = true;
            bird_x_ = kScreenWidth;
            bird_y_offset_ = 0;
            bird_y_velocity_ =
                easy_mode_ ? 0 : static_cast<int8_t>((std::rand() % 3) - 1);
            bird_up_ = false;
        }
        return;
    }

    bird_x_ = static_cast<int16_t>(bird_x_ - (kGameSpeedBase + speed_modifier_ + 1));

    if (!easy_mode_) {
        bird_y_offset_ = static_cast<int16_t>(bird_y_offset_ + bird_y_velocity_);
        if ((std::rand() % 30) == 0)
            bird_y_velocity_ = static_cast<int8_t>((std::rand() % 3) - 1);

        const int base_y = bird_up_ ? kBirdYUp : kBirdYDown;
        int current_y = base_y + bird_y_offset_;
        const int lo = kGameAreaTop + 10;
        const int hi = kGroundY - kBirdH - 10;
        if (current_y < lo) {
            bird_y_offset_ = static_cast<int16_t>(lo - base_y);
            bird_y_velocity_ = 1;
        } else if (current_y > hi) {
            bird_y_offset_ = static_cast<int16_t>(hi - base_y);
            bird_y_velocity_ = -1;
        }
    }

    if ((steps_ % 15) == 0) bird_flop_ = !bird_flop_;

    if (bird_x_ < -kBirdW - 5) bird_in_game_ = false;
}

void DinoGameView::check_collision() {
    if (obstacle_.active &&
        dino_logic::dino_collides(jump_.height, ducking_, obstacle_)) {
        collided_ = true;
        return;
    }

    if (bird_in_game_) {
        int dino_left = kDinoX + 5;
        int dino_right = kDinoX + (ducking_ ? kDinoDuckWidth : kDinoWidth) - 5;
        int dino_top = (ducking_ ? kDinoDuckY : (kDinoY - jump_.height)) + 5;
        int dino_bottom =
            (ducking_ ? kDinoDuckY : (kDinoY - jump_.height)) +
            (ducking_ ? kDinoDuckHeight : kDinoHeight) - 5;

        /* In easy mode the bird flies at a fixed duck-under height. */
        const int bird_y = easy_mode_
                               ? (kDinoY - 10)
                               : (bird_up_ ? kBirdYUp : kBirdYDown) + bird_y_offset_;

        if (dino_right > bird_x_ + 5 &&
            dino_left < bird_x_ + kBirdW - 5 &&
            dino_bottom > bird_y + 5 &&
            dino_top < bird_y + kBirdH - 5) {
            collided_ = true;
        }
    }
}

void DinoGameView::game_loop() {
    if (collided_) {
        state_ = State::GAME_OVER;
        if (score_ > high_score_) high_score_ = score_;
        return;
    }

    ground_offset_ = static_cast<uint8_t>(
        (ground_offset_ + kGameSpeedBase + speed_modifier_) % 20);

    update_obstacle();
    manage_bird();
    jump_.step(speed_modifier_);

    if (ducking_ && duck_timer_ > 0) {
        --duck_timer_;
        if (duck_timer_ == 0) ducking_ = false;
    }

    const int anim_period = 10 - speed_modifier_;
    if (anim_period > 0 && (steps_ % static_cast<uint32_t>(anim_period)) == 0)
        run_frame_ = !run_frame_;

    check_collision();

    score_ = steps_ / 10;
    if (score_ > 0 && (score_ % 100) == 0 && (steps_ % 1000) == 0) {
        if (speed_modifier_ < 5) ++speed_modifier_;
    }

    ++steps_;
}

void DinoGameView::on_frame_sync() {
    View::on_frame_sync();
    if (state_ == State::PLAYING) game_loop();
    else ++blink_counter_;
    set_dirty();
}

bool DinoGameView::on_key(const ui::KeyEvent key) {
    if (key == ui::KeyEvent::Back) return false;  /* let the framework exit */

    switch (key) {
        case ui::KeyEvent::Select:
            if (state_ == State::MENU) {
                new_game();
                state_ = State::PLAYING;
            } else if (state_ == State::PLAYING && !collided_) {
                jump_.start();
                if (ducking_) {
                    ducking_ = false;
                    duck_timer_ = 0;
                }
            } else {  /* GAME_OVER */
                new_game();
                state_ = State::PLAYING;
            }
            break;

        case ui::KeyEvent::Down:
            if (state_ == State::PLAYING && !collided_ && !jump_.jumping) {
                ducking_ = true;
                duck_timer_ = 60;  /* auto-stand after ~1s */
            }
            break;

        case ui::KeyEvent::Up:
            if (state_ == State::PLAYING && !collided_) {
                ducking_ = false;
                duck_timer_ = 0;
            }
            break;

        case ui::KeyEvent::Left:
        case ui::KeyEvent::Right:
            if (state_ == State::MENU) easy_mode_ = !easy_mode_;
            break;

        default:
            break;
    }

    set_dirty();
    return true;
}

