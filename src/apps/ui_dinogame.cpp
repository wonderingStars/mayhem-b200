/* Sprite geometry (matches upstream's draw code, which for the ducking frames
 * reads a 45x22 window out of the larger stored array). */
constexpr int kDinoW = dino_logic::kDinoWidth;    /* 34 */
constexpr int kDinoH = dino_logic::kDinoHeight;   /* 36 */
constexpr int kDuckW = dino_logic::kDinoDuckWidth;  /* 45 */
constexpr int kDuckH = dino_logic::kDinoDuckHeight; /* 22 */
constexpr int kBirdW = 34;
constexpr int kBirdH = 27;

constexpr uint16_t kTransparent = 0xFFFF;
constexpr uint16_t kSpriteColor = 0x528A;

/* Bird flight bands, as upstream init_dimensions() computes them for 240x320. */
constexpr int kBirdYUp = dino_logic::kGameAreaTop + 20;                            /* 100 */
constexpr int kBirdYDown = dino_logic::kGameAreaTop + dino_logic::kGameAreaHeight * 60 / 160; /* 140 */

constexpr int kMinObstacleDist = dino_logic::kScreenWidth * 300 / 240;  /* 300 */
constexpr int kMaxObstacleDist = dino_logic::kScreenWidth * 600 / 240;  /* 600 */

std::string zero_pad5(uint32_t v) {
    std::string s = std::to_string(v);
    if (s.size() < 5) s = std::string(5 - s.size(), '0') + s;
    return s;
}

