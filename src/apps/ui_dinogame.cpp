void DinoGameView::draw_sprite(ui::Painter& painter, ui::Point origin, int x,
                               int y, const uint16_t* sprite, int w, int h,
                               bool bird) {
    for (int dy = 0; dy < h; ++dy) {
        for (int dx = 0; dx < w; ++dx) {
            uint16_t px = sprite[dy * w + dx];
            if (px == kTransparent) continue;
            if (bird && px == kSpriteColor) px = ui::Color::red().v;
            painter.fill_rectangle(
                {origin.x() + x + dx, origin.y() + y + dy, 1, 1}, ui::Color(px));
        }
    }
}

void DinoGameView::draw_obstacle(ui::Painter& painter, ui::Point origin) {
    if (!obstacle_.active) return;
    const int ox = origin.x() + obstacle_.x;
    const int gy = origin.y() + kGroundY;
    const int y = gy - obstacle_.height;
    const ui::Color g = ui::Color::green();
    const ui::Color dg = ui::Color::dark_green();

    auto fr = [&](int x1, int y1, int x2, int y2) {
        painter.fill_rectangle({x1, y1, x2 - x1, y2 - y1}, g);
    };

    switch (obstacle_.width) {
        case 15:  /* small single */
            fr(ox + 5, y, ox + 10, gy);
            fr(ox, y + 8, ox + 5, y + 15);
            fr(ox + 10, y + 12, ox + 15, y + 19);
            painter.draw_vline({ox + 4, y + 8}, 7, dg);
            painter.draw_vline({ox + 10, y + 12}, 7, dg);
            break;
        case 20:  /* large single */
            fr(ox + 7, y, ox + 13, gy);
            fr(ox, y + 10, ox + 7, y + 20);
            fr(ox + 13, y + 15, ox + 20, y + 25);
            painter.draw_vline({ox + 6, y}, gy - y, dg);
            painter.draw_vline({ox + 13, y}, gy - y, dg);
            break;
        case 35:  /* double */
            fr(ox + 5, y + 5, ox + 10, gy);
            fr(ox + 20, y, ox + 25, gy);
            fr(ox, y + 12, ox + 5, y + 18);
            fr(ox + 10, y + 15, ox + 15, y + 22);
            fr(ox + 25, y + 10, ox + 30, y + 17);
            painter.draw_vline({ox + 19, y}, gy - y, dg);
            break;
        default:  /* 45: triple */
            fr(ox + 5, y + 8, ox + 10, gy);
            fr(ox + 20, y, ox + 25, gy);
            fr(ox + 35, y + 5, ox + 40, gy);
            fr(ox, y + 15, ox + 5, y + 20);
            fr(ox + 25, y + 8, ox + 30, y + 15);
            fr(ox + 40, y + 12, ox + 45, y + 18);
            painter.draw_vline({ox + 19, y}, gy - y, dg);
            break;
    }
}

void DinoGameView::draw_playfield(ui::Painter& painter, ui::Point origin) {
    /* ground line + moving texture */
    const int gy = origin.y() + kGroundY;
    painter.draw_hline({origin.x(), gy}, kScreenWidth, ui::Color::white());
    painter.draw_hline({origin.x(), gy + 1}, kScreenWidth, ui::Color::dark_grey());
    for (int x = -static_cast<int>(ground_offset_); x < kScreenWidth; x += 20) {
        painter.draw_hline({origin.x() + x, gy + 3}, 10, ui::Color::dark_grey());
        painter.draw_hline({origin.x() + x + 5, gy + 5}, 5, ui::Color::dark_grey());
    }

    draw_obstacle(painter, origin);

    /* bird */
    if (bird_in_game_) {
        const int base_y = easy_mode_ ? (kDinoY - 10)
                                      : (bird_up_ ? kBirdYUp : kBirdYDown) + bird_y_offset_;
        const uint16_t* spr = bird_flop_ ? pterodactyl_upflop : pterodactyl_downflop;
        draw_sprite(painter, origin, bird_x_, base_y, spr, kBirdW, kBirdH, true);
    }

    /* dino */
    const int dino_y =
        jump_.jumping ? (kDinoY - jump_.height) : (ducking_ ? kDinoDuckY : kDinoY);
    const uint16_t* spr;
    int w = kDinoW, h = kDinoH;
    if (jump_.jumping) {
        spr = dino_default;
    } else if (ducking_) {
        spr = run_frame_ ? dino_ducking_leftstep : dino_ducking_rightstep;
        w = kDuckW;
        h = kDuckH;
    } else {
        spr = run_frame_ ? dino_leftstep : dino_rightstep;
    }
    draw_sprite(painter, origin, kDinoX, dino_y, spr, w, h, false);

    /* scores */
    const ui::Style* style = ui::Theme::getInstance()->fg_light;
    painter.draw_string({origin.x() + 10, origin.y() + 12}, *style,
                        score_to_string(score_));
    painter.draw_string({origin.x() + kScreenWidth - 90, origin.y() + 12}, *style,
                        "HI " + score_to_string(high_score_));
}

void DinoGameView::paint(ui::Painter& painter) {
    const ui::Point origin = screen_pos();
    painter.fill_rectangle(screen_rect(), ui::Color::black());

    const ui::Style* style = ui::Theme::getInstance()->fg_light;
    const int cw = ui::char_width;
    auto centered = [&](const std::string& s) {
        return origin.x() + kScreenWidth / 2 - static_cast<int>(s.size()) * cw / 2;
    };

    if (state_ == State::MENU) {
        painter.draw_string({centered("DINO GAME"), origin.y() + 40}, *style,
                            "DINO GAME");

        /* animated dino */
        const bool frame = (blink_counter_ / 10) % 2;
        const int dino_x = kScreenWidth / 2 - kDinoW / 2;
        draw_sprite(painter, origin, dino_x, 70,
                    frame ? dino_leftstep : dino_rightstep, kDinoW, kDinoH, false);

        painter.draw_string({centered("SELECT: Jump / Start"), origin.y() + 120},
                            *style, "SELECT: Jump / Start");
        painter.draw_string({centered("DOWN: Duck   UP: Stand"), origin.y() + 140},
                            *style, "DOWN: Duck   UP: Stand");
        painter.draw_string({centered("L/R: toggle mode"), origin.y() + 160}, *style,
                            "L/R: toggle mode");

        const std::string mode = easy_mode_ ? "Mode: EASY" : "Mode: HARD";
        painter.draw_string({centered(mode), origin.y() + 190}, *style, mode);

        painter.draw_string({centered("HI " + score_to_string(high_score_)),
                             origin.y() + 220},
                            *style, "HI " + score_to_string(high_score_));

        if ((blink_counter_ / 30) % 2 == 0)
            painter.draw_string({centered("* PRESS SELECT *"), origin.y() + 260},
                                *style, "* PRESS SELECT *");
        return;
    }

    if (state_ == State::PLAYING) {
        draw_playfield(painter, origin);
        return;
    }

    /* GAME_OVER */
    const int cx = kScreenWidth / 2 - kDinoW / 2;
    draw_sprite(painter, origin, cx, kGameAreaTop, dino_gameover,
                kDinoW, kDinoH, false);
    painter.draw_string({centered("GAME OVER"), origin.y() + kGameAreaTop + 50},
                        *style, "GAME OVER");
    const std::string sc = "SCORE: " + score_to_string(score_);
    painter.draw_string({centered(sc), origin.y() + kGameAreaTop + 70}, *style, sc);
    painter.draw_string({centered("SELECT to retry"), origin.y() + kGameAreaTop + 95},
                        *style, "SELECT to retry");
    if (score_ >= high_score_)
        painter.draw_string({centered("NEW HIGH SCORE!"),
                             origin.y() + kGameAreaTop + 115},
                            *style, "NEW HIGH SCORE!");
}

